    public ExpenseReport Report { get; }
    public string Language { get; }

    private PdfLabels Labels => Locales.TryGetValue(Language, out var labels) ? labels : Locales["fr"];

    private string CurrencySymbol => InternationalMileageCalculator.GetCurrencySymbol(Report.Currency);

    private string ScaleName => InternationalMileageCalculator.GetPresetOrDefault(Report.CountryScale).Name;

    public ExpenseReportPdfDocument(ExpenseReport report, string? lang = null)
    {
        Report = report;
        Language = ResolveLanguage(lang);
    }

    public static void RegisterLocale(string langCode, PdfLabels labels)
    {
        if (!string.IsNullOrWhiteSpace(langCode))
        {
            Locales[langCode.Trim().ToLowerInvariant()] = labels;
        }
    }

    private static string ResolveLanguage(string? lang)
    {
        if (!string.IsNullOrWhiteSpace(lang))
        {
            var normalized = lang.Trim().ToLowerInvariant();
            if (normalized.Length >= 2)
            {
                var twoLetter = normalized[..2];
                if (Locales.ContainsKey(twoLetter))
                {
                    return twoLetter;
                }
            }
        }

        return "fr";
    }

    public DocumentMetadata GetMetadata() => DocumentMetadata.Default;
    public DocumentSettings GetSettings() => DocumentSettings.Default;

    public void Compose(IDocumentContainer container)
    {
        container.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(30);
            page.PageColor(Colors.White);
            page.DefaultTextStyle(x => x.FontSize(9));

            page.Header().Element(ComposeHeader);
            page.Content().Element(ComposeContent);
            page.Footer().Element(ComposeFooter);
        });
    }

    private void ComposeHeader(IContainer container)
    {
        var l = Labels;

        container.Column(col =>
        {
            col.Item().Row(row =>
            {
                row.RelativeItem().Column(titleCol =>
                {
                    titleCol.Item().Text(l.DocumentTitle)
                        .FontSize(15).Bold().FontColor(Colors.Blue.Darken3);

                    titleCol.Item().Text($"Réf : NDF-{Report.Id:D5} | {Report.Title}")
                        .FontSize(10).SemiBold().FontColor(Colors.Grey.Darken2);

                    var periodText = string.Format(
                        System.Globalization.CultureInfo.InvariantCulture,
                        l.PeriodFormat,
                        Report.PeriodStart,
                        Report.PeriodEnd);

                    titleCol.Item().Text($"{periodText} | {l.ScaleLabel} : {ScaleName} ({Report.Currency})")
                        .FontSize(8.5f).FontColor(Colors.Grey.Darken1);
                });

                row.ConstantItem(140).Column(statusCol =>
                {
                    var statusColor = Report.Status switch
                    {
                        ReportStatus.Approved => Colors.Green.Darken2,
                        ReportStatus.Submitted => Colors.Orange.Darken2,
                        ReportStatus.Rejected => Colors.Red.Darken2,
                        _ => Colors.Grey.Darken2
                    };

                    var statusText = Report.Status switch
                    {
                        ReportStatus.Approved => l.StatusApproved,
                        ReportStatus.Submitted => l.StatusSubmitted,
                        ReportStatus.Rejected => l.StatusRejected,
                        _ => l.StatusDraft
                    };

                    statusCol.Item().Border(1).BorderColor(statusColor).Padding(6).AlignCenter()
                        .Text(statusText).FontSize(11).Bold().FontColor(statusColor);
                });
            });

            col.Item().PaddingTop(12).LineHorizontal(1).LineColor(Colors.Grey.Lighten1);

            // Coordonnées Salarié & Entreprise
            col.Item().PaddingTop(8).Row(row =>
            {
                row.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(8).Column(empCol =>
                {
                    empCol.Item().Text(l.BeneficiaryHeader).FontSize(8).Bold().FontColor(Colors.Grey.Darken2);
                    empCol.Item().Text(string.IsNullOrWhiteSpace(Report.EmployeeName) ? l.UnspecifiedPerson : Report.EmployeeName).Bold();
                    if (!string.IsNullOrWhiteSpace(Report.EmployeeEmail))
                    {
                        empCol.Item().Text(Report.EmployeeEmail).FontColor(Colors.Grey.Darken1);
                    }
                });

                row.ConstantItem(15);

                row.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(8).Column(compCol =>
                {
                    compCol.Item().Text(l.CompanyHeader).FontSize(8).Bold().FontColor(Colors.Grey.Darken2);
                    compCol.Item().Text(string.IsNullOrWhiteSpace(Report.CompanyName) ? l.UnspecifiedCompany : Report.CompanyName).Bold();
                    compCol.Item().Text($"{l.IssueDateLabel} : {DateTime.UtcNow:dd/MM/yyyy}").FontColor(Colors.Grey.Darken1);
                });
            });

            col.Item().PaddingBottom(12);
        });
    }

    private void ComposeContent(IContainer container)
    {
        var symbol = CurrencySymbol;
        var l = Labels;

        container.Column(col =>
        {
            // Section 1 : Trajets & Kilomètres
            col.Item().PaddingTop(6).Text(l.Section1Title)
                .FontSize(11).Bold().FontColor(Colors.Blue.Darken2);

            if (Report.Trips.Count == 0)
            {
                col.Item().Padding(8).Text(l.NoTripsMessage).Italic().FontColor(Colors.Grey.Darken1);
            }
            else
            {
                col.Item().PaddingTop(4).Table(table =>
                {
                    table.ColumnsDefinition(columns =>
                    {
                        columns.ConstantColumn(65);  // Date
                        columns.RelativeColumn(2);   // Motif / Lieu
                        columns.RelativeColumn(3);   // Trajet (De -> A)
                        columns.ConstantColumn(45);  // Type
                        columns.ConstantColumn(50);  // Distance
                        columns.ConstantColumn(70);  // Montant
                    });

                    table.Header(header =>
                    {
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColDate).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColPurpose).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColItinerary).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColRoundTrip).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).AlignRight().Text(l.ColKm).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).AlignRight().Text(l.ColTotalIk).Bold();
                    });

                    foreach (var trip in Report.Trips.OrderBy(t => t.Date))
                    {
                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).Text($"{trip.Date:dd/MM/yyyy}");

                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).Column(mCol =>
                        {
                            mCol.Item().Text(trip.Purpose).Bold();
                            if (!string.IsNullOrWhiteSpace(trip.ClientOrLocation))
                                mCol.Item().Text(trip.ClientOrLocation).FontSize(8).FontColor(Colors.Grey.Darken1);
                        });

                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4)
                            .Text($"{trip.DepartureAddress} -> {trip.ArrivalAddress}");

                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4)
                            .Text(trip.IsRoundTrip ? l.RoundTripYes : l.RoundTripNo);

                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).AlignRight()
                            .Text($"{trip.TotalDistanceKm:N1} km");

                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).AlignRight()
                            .Text($"{trip.CalculatedAmount:N2} {symbol}").Bold();
                    }
                });

                // Sous-total IK
                col.Item().PaddingTop(4).AlignRight().Text(text =>
                {
                    text.Span($"{l.TotalKmLabel} : {Report.TotalDistanceKm:N1} km  |  ").SemiBold();
                    text.Span($"{l.SubtotalIkLabel} : {Report.TotalMileageAmount:N2} {symbol}").Bold().FontColor(Colors.Blue.Darken3);
                });
            }

            // Section 2 : Frais annexes (Péages, Parking, Repas)
            col.Item().PaddingTop(14).Text(l.Section2Title)
                .FontSize(11).Bold().FontColor(Colors.Blue.Darken2);

            if (Report.Receipts.Count == 0)
            {
                col.Item().Padding(8).Text(l.NoReceiptsMessage).Italic().FontColor(Colors.Grey.Darken1);
            }
            else
            {
                col.Item().PaddingTop(4).Table(table =>
                {
                    table.ColumnsDefinition(columns =>
                    {
                        columns.ConstantColumn(65);  // Date
                        columns.ConstantColumn(85);  // Catégorie
                        columns.RelativeColumn(3);   // Commerçant / Détail
                        columns.ConstantColumn(60);  // Justificatif
                        columns.ConstantColumn(70);  // Montant TTC
                    });

                    table.Header(header =>
                    {
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColDate).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColCategory).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColMerchant).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).Text(l.ColReceiptAttached).Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(4).AlignRight().Text(l.ColTtc).Bold();
                    });

                    foreach (var receipt in Report.Receipts.OrderBy(r => r.Date))
                    {
                        var catName = receipt.Category switch
                        {
                            ReceiptCategory.Toll => l.CategoryToll,
                            ReceiptCategory.Parking => l.CategoryParking,
                            ReceiptCategory.Meal => l.CategoryMeal,
                            ReceiptCategory.Fuel => l.CategoryFuel,
                            ReceiptCategory.Hotel => l.CategoryHotel,
                            _ => l.CategoryOther
                        };

                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).Text($"{receipt.Date:dd/MM/yyyy}");
                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).Text(catName);
                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).Text(receipt.Merchant);
                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4)
                            .Text(!string.IsNullOrEmpty(receipt.ReceiptImagePath) ? l.AttachedYes : l.AttachedNo);
                        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(4).AlignRight()
                            .Text($"{receipt.AmountTtc:N2} {symbol}").Bold();
                    }
                });

                // Sous-total Reçus
                col.Item().PaddingTop(4).AlignRight().Text(text =>
                {
                    text.Span($"{l.SubtotalReceiptsLabel} : {Report.TotalReceiptsAmount:N2} {symbol}").Bold().FontColor(Colors.Blue.Darken3);
                });
            }

            // Récapitulatif Final & Calcul du Remboursement
            col.Item().PaddingTop(16).Border(1.5f).BorderColor(Colors.Blue.Darken2).Background(Colors.Blue.Lighten5).Padding(10).Column(recapCol =>
            {
                recapCol.Item().Row(r =>
                {
                    r.RelativeItem().Text(l.RecapTotalIk);
                    r.ConstantItem(110).AlignRight().Text($"{Report.TotalMileageAmount:N2} {symbol}");
                });
                recapCol.Item().Row(r =>
                {
                    r.RelativeItem().Text(l.RecapTotalReceipts);
                    r.ConstantItem(110).AlignRight().Text($"{Report.TotalReceiptsAmount:N2} {symbol}");
                });
                recapCol.Item().Row(r =>
                {
                    r.RelativeItem().Text(l.RecapTotalGross).Bold();
                    r.ConstantItem(110).AlignRight().Text($"{Report.TotalGrossAmount:N2} {symbol}").Bold();
                });

                if (Report.ReimbursementRatePercentage < 100m)
                {
                    recapCol.Item().Row(r =>
                    {
                        r.RelativeItem().Text($"{l.RecapEmployerRate} ({Report.ReimbursementRatePercentage:N0}%) :")
                            .FontColor(Colors.Orange.Darken3);
                        r.ConstantItem(110).AlignRight().Text($"{Report.ReimbursementRatePercentage:N0} %")
                            .FontColor(Colors.Orange.Darken3);
                    });
                }

                recapCol.Item().PaddingTop(4).LineHorizontal(1).LineColor(Colors.Blue.Lighten1);

                recapCol.Item().PaddingTop(4).Row(r =>
                {
                    r.RelativeItem().Text(l.RecapNetToReimburse).FontSize(11).Bold().FontColor(Colors.Blue.Darken3);
                    r.ConstantItem(130).AlignRight().Text($"{Report.TotalReimbursableAmount:N2} {symbol}").FontSize(12).Bold().FontColor(Colors.Blue.Darken3);
                });
            });

            // Signatures
            col.Item().PaddingTop(20).Row(signRow =>
            {
                signRow.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(8).Height(65).Column(s =>
                {
                    s.Item().Text(l.EmployeeSignatureTitle).FontSize(8).Bold();
                    s.Item().Text(l.EmployeeSignatureNote).FontSize(7).Italic().FontColor(Colors.Grey.Darken1);
                });

                signRow.ConstantItem(20);

                signRow.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(8).Height(65).Column(s =>
                {
                    s.Item().Text(l.ManagerSignatureTitle).FontSize(8).Bold();
                    s.Item().Text(l.ManagerSignatureNote).FontSize(7).Italic().FontColor(Colors.Grey.Darken1);
                });
            });
        });
    }

    private void ComposeFooter(IContainer container)
    {
        var l = Labels;

        container.Row(row =>
        {
            row.RelativeItem().Text(x =>
            {
                x.Span($"{l.FooterAutoGenerated} : {ScaleName} ({Report.Currency}).")
                    .FontSize(7).FontColor(Colors.Grey.Darken1);
            });

            row.RelativeItem().AlignRight().Text(x =>
            {
                x.Span("Page ");
                x.CurrentPageNumber();
                x.Span(" / ");
                x.TotalPages();
            });
        });
    }
